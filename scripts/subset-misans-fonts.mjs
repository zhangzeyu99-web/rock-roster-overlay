import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const archive = path.join(root, "misans-4.1.0.tgz");
const tmpDir = path.join(root, ".tmp-misans");
const sourceDir = path.join(tmpDir, "package", "lib", "Normal");
const outputDir = path.join(root, "src", "renderer", "fonts");
const cssFiles = ["MiSans-Regular.min.css", "MiSans-Bold.min.css"];
const sampleText =
  "洛克王国世界阵容叠加器左右队双队单列全屏透明窗口采集战败灰度属性图标名字样式世界实战雾蓝压条柔石灰联赛夜金化蝶鳄鱼海枝枝";

if (!fs.existsSync(archive)) {
  throw new Error(`MiSans archive is missing: ${archive}`);
}

fs.rmSync(tmpDir, { recursive: true, force: true });
fs.mkdirSync(tmpDir, { recursive: true });
execFileSync(
  "tar",
  [
    "-xzf",
    archive,
    "-C",
    tmpDir,
    ...cssFiles.map((file) => `package/lib/Normal/${file}`)
  ],
  { stdio: "inherit" }
);

const codePoints = new Set();
collectText(sampleText);
collectJson(path.join(root, "seed-data", "data", "pets.json"));
collectJson(path.join("C:", "Users", "Administrator", "Documents", "RockRosterOverlay", "data", "pets.json"));

const selectedRules = [];
const selectedFiles = new Set();

for (const cssFile of cssFiles) {
  const css = fs.readFileSync(path.join(sourceDir, cssFile), "utf8");
  for (const rule of parseFontFaceRules(css)) {
    if (!ruleMatchesUsedText(rule.unicodeRanges)) {
      continue;
    }
    selectedRules.push(rule.css.replace(/font-family:MiSans/g, 'font-family:"MiSans"'));
    selectedFiles.add(rule.fileName);
  }
}

if (selectedFiles.size === 0) {
  throw new Error("No MiSans font shards matched current text set");
}

const listFile = path.join(tmpDir, "font-list.txt");
fs.writeFileSync(
  listFile,
  Array.from(selectedFiles)
    .sort()
    .map((file) => `package/lib/Normal/${file}`)
    .join("\n"),
  "utf8"
);
execFileSync("tar", ["-xzf", archive, "-C", tmpDir, "-T", listFile], { stdio: "inherit" });

fs.rmSync(outputDir, { recursive: true, force: true });
fs.mkdirSync(outputDir, { recursive: true });
for (const fileName of selectedFiles) {
  fs.copyFileSync(path.join(sourceDir, fileName), path.join(outputDir, fileName));
}
fs.writeFileSync(
  path.join(outputDir, "misans.css"),
  [
    "/* Generated by scripts/subset-misans-fonts.mjs from local MiSans package. */",
    ...selectedRules
  ].join("\n"),
  "utf8"
);

console.log(`MiSans subset ready: ${selectedFiles.size} shards`);

function collectJson(filePath) {
  if (!fs.existsSync(filePath)) {
    return;
  }
  const value = JSON.parse(fs.readFileSync(filePath, "utf8"));
  collectValue(value);
}

function collectValue(value) {
  if (typeof value === "string") {
    collectText(value);
    return;
  }
  if (Array.isArray(value)) {
    for (const item of value) {
      collectValue(item);
    }
    return;
  }
  if (value && typeof value === "object") {
    for (const item of Object.values(value)) {
      collectValue(item);
    }
  }
}

function collectText(text) {
  for (const char of text) {
    codePoints.add(char.codePointAt(0));
  }
}

function parseFontFaceRules(css) {
  const matches = css.matchAll(/@font-face\{[^}]+}/g);
  return Array.from(matches, (match) => {
    const ruleCss = match[0].replace(/url\('([^']+)'\)/, "url('./$1')");
    const fileName = ruleCss.match(/url\('\.\/([^']+)'\)/)?.[1];
    const unicodeRange = ruleCss.match(/unicode-range:([^;]+);/)?.[1] ?? "";
    return {
      css: ruleCss,
      fileName,
      unicodeRanges: parseUnicodeRanges(unicodeRange)
    };
  }).filter((rule) => rule.fileName);
}

function parseUnicodeRanges(value) {
  return value.split(",").map((part) => {
    const raw = part.trim().replace(/^U\+/i, "");
    if (raw.includes("?")) {
      const min = Number.parseInt(raw.replace(/\?/g, "0"), 16);
      const max = Number.parseInt(raw.replace(/\?/g, "F"), 16);
      return [min, max];
    }
    const [start, end = start] = raw.split("-");
    return [Number.parseInt(start, 16), Number.parseInt(end, 16)];
  });
}

function ruleMatchesUsedText(ranges) {
  for (const point of codePoints) {
    if (ranges.some(([start, end]) => point >= start && point <= end)) {
      return true;
    }
  }
  return false;
}
